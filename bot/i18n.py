def normalize_locale(locale: str | None) -> str:
    if not locale:
        return DEFAULT_LOCALE
    value = locale.strip().lower()
    if value in SUPPORTED_LOCALES:
        return value
    return DEFAULT_LOCALE


def locale_label(locale: str | None) -> str:
    return LOCALE_LABELS[normalize_locale(locale)]


def t(locale: str | None, key: str, **kwargs: Any) -> str:
    normalized = normalize_locale(locale)
    template = (
        _EXTRA_MESSAGES.get(normalized, {}).get(key)
        or _MESSAGES.get(normalized, {}).get(key)
        or _EXTRA_MESSAGES[DEFAULT_LOCALE].get(key)
        or _MESSAGES[DEFAULT_LOCALE].get(key)
        or key
    )
    if kwargs:
        return template.format(**kwargs)
    return template
