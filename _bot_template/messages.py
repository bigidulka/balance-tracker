def USER_INFO(user_id: int, username: str | None) -> str:
    """Информация о пользователе"""
    name = f"@{username}" if username else f"ID: {user_id}"
    return f"👤 Пользователь: {name}"


def ITEM_COUNT(count: int) -> str:
    """Количество элементов"""
    if count == 0:
        return "Нет элементов"
    elif count == 1:
        return "1 элемент"
    elif 2 <= count <= 4:
        return f"{count} элемента"
    else:
        return f"{count} элементов"
